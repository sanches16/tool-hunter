#!/usr/bin/env bash
# Writes workflow-owned evidence into docs/poc/PLATFORM-POC-001-RESULT.md
# (created by T021) between marker comments, replacing earlier content of the
# same block. Only sanitized data from .agent-out/evidence/*.json, Git and run
# state is written. Committing is done by the following commit-push step.
#
# Usage:
#   record-evidence.sh results <label>            local + Docker + CI evidence
#   record-evidence.sh report <name> <path>       link a revision-linked review report
#   record-evidence.sh metrics <run_id> <k=v>...  FR-013 metrics (owner-supplied values)
source "$(dirname "$0")/lib.sh"
mode="${1:?usage: record-evidence.sh results|report|metrics ...}"; shift
[ -f "$RESULT_FILE" ] || fail "$RESULT_FILE missing (created by T021)"

# put_block <name> <file-with-markdown>: replace or append a marked block.
put_block() {
  python3 - "$RESULT_FILE" "$1" "$2" <<'EOF'
import sys, re
path, name, src = sys.argv[1:4]
text = open(path, encoding="utf-8").read()
body = open(src, encoding="utf-8").read().rstrip("\n")
start, end = f"<!-- workflow-evidence:{name}:start -->", f"<!-- workflow-evidence:{name}:end -->"
block = f"{start}\n{body}\n{end}"
pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
if pattern.search(text):
    text = pattern.sub(lambda _: block, text)
else:
    heading = "## Workflow-recorded evidence"
    if heading not in text:
        text = text.rstrip("\n") + f"\n\n{heading}\n\nWritten by the platform-poc-001 workflow (trusted shell), not by agents.\n"
    text = text.rstrip("\n") + f"\n\n{block}\n"
open(path, "w", encoding="utf-8").write(text)
EOF
}

tmpmd="$(mktemp)"; trap 'rm -f "$tmpmd"' EXIT
now="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

case "$mode" in
results)
  label="${1:?label}"
  local_ev="$EVIDENCE_DIR/local-checks.json"; docker_ev="$EVIDENCE_DIR/docker-health.json"; ci_ev="$EVIDENCE_DIR/ci.json"
  for f in "$local_ev" "$docker_ev" "$ci_ev"; do [ -s "$f" ] || fail "$f missing"; done
  sha="$(jq -r .implementation_sha "$ci_ev")"
  code_tree="$(git rev-parse "$sha^{tree}")"
  for f in "$local_ev" "$docker_ev"; do
    [ "$(jq -r .worktree_tree "$f")" = "$code_tree" ] || fail "$f was produced on a different tree than $sha"
  done
  pass "local and Docker evidence were produced on the exact tree of $sha"
  {
    echo "### Verification evidence ($label)"
    echo
    echo "- Tested implementation commit: \`$sha\` (tree \`$code_tree\`)"
    echo "- Recorded: $now by workflow step \`record-results\`; this text is committed separately in a records-only commit."
    jq -r '"- Tools: node \(.tools.node), npm \(.tools.npm), \(.tools.docker), compose \(.tools.compose)"' "$local_ev"
    jq -r '"- Lockfile generated by workflow (`npm install --package-lock-only --ignore-scripts`): \(.lockfile_generated_by_workflow)"' "$local_ev"
    jq -r 'if ((.files_changed_by_checks // []) | length) > 0 then "- Files regenerated by the checks and included in the tested commit: \(.files_changed_by_checks | join(", "))" else "- The checks changed no repository files" end' "$local_ev"
    echo
    echo "#### Local checks (shell \`local-checks\`)"
    echo
    echo "| Check | Command | Result | Exit | Duration ms | Safe summary | Criteria |"
    echo "|---|---|---|---:|---:|---|---|"
    jq -r '
      {install:"FR-001, FR-009; SC-004", lint:"FR-009; SC-004; AC-05", typecheck:"FR-009; SC-004; AC-06",
       build:"FR-009; SC-004; AC-07", test:"FR-002–FR-005, FR-009; SC-002–SC-004; AC-08",
       "verify-startup":"FR-001, FR-009; SC-001, SC-004"} as $map
      | .checks[] | "| \(.name) | `\(.command)` | \(.result) | \(.exit_code) | \(.duration_ms) | \(.summary // "" | if . == "" then "—" else . end) | \($map[.name] // "") |"' "$local_ev"
    echo
    echo "#### Docker lifecycle (shell \`docker-health\`, ephemeral project \`$(jq -r .compose_project "$docker_ev")\`)"
    echo
    echo "| Criterion | Result | Observation | Criteria |"
    echo "|---|---|---|---|"
    jq -r '
      {"compose-startup":"FR-001, FR-006; SC-001; AC-02", "healthy-200":"FR-002, FR-003; SC-002; AC-03",
       "db-stopped-503":"FR-004, FR-005; SC-002, SC-003; AC-04", "db-restarted-200":"FR-002, FR-004; SC-002",
       "same-app-process":"FR-004; SC-002", "app-stopped-no-response":"FR-008; US1.A5", "cleanup":"FR-007"} as $map
      | .checks[] | "| \(.criterion) | \(.result) | \(.detail) | \($map[.criterion] // "") |"' "$docker_ev"
    echo
    echo "#### GitHub Actions (shell \`ci\`)"
    echo
    jq -r '"- Run: \(.run_url // "none") — conclusion **\(.conclusion)** for `\(.implementation_sha)`",
           (.jobs[] | "- Job `\(.name)`: \(.conclusion) — \(.url)"),
           "- Core checks: lint \(.core_checks.lint), typecheck \(.core_checks.typecheck), build \(.core_checks.build), test \(.core_checks.test), verify:startup \(.core_checks["verify:startup"])",
           "- Criteria: FR-010, FR-011; SC-005; AC-09"' "$ci_ev"
  } > "$tmpmd"
  put_block "verification" "$tmpmd"
  ;;

report)
  name="${1:?name}"; path="${2:?path}"   # path "-" records "not performed"
  [ "$path" = "-" ] || [ -s "$path" ] || fail "$path missing"
  code_sha="$(jq -r '.implementation_sha // empty' "$EVIDENCE_DIR/ci.json" 2>/dev/null || true)"
  existing="$(python3 - "$RESULT_FILE" <<'EOF'
import sys, re
t = open(sys.argv[1], encoding="utf-8").read()
m = re.search(r"<!-- workflow-evidence:reports:start -->\n(.*?)\n<!-- workflow-evidence:reports:end -->", t, re.S)
print(m.group(1) if m else "### Review reports")
EOF
)"
  {
    printf '%s\n' "$existing" | grep -v "^- $name:" || true
    if [ "$path" = "-" ]; then
      echo "- $name: not performed (optional stage unavailable or failed), recorded $now"
    else
      echo "- $name: [\`$path\`](../../$path) — reviewed implementation commit \`${code_sha:-unknown}\` at HEAD \`$(git rev-parse --short HEAD)\`, recorded $now"
    fi
  } > "$tmpmd"
  put_block "reports" "$tmpmd"
  ;;

metrics)
  run_id="${1:?run_id}"; shift
  # bash 3.2 (macOS) has no associative arrays: look values up in "$@".
  args=("$@")
  val() { local kv; for kv in "${args[@]}"; do [ "${kv%%=*}" = "$1" ] && { printf '%s' "${kv#*=}"; return; }; done; }
  counts=(manual_copy_paste context_reexplained converge_gaps grok_unique_findings claude_scope_deviations broken_sdd_artifacts)
  ratings=(installation_difficulty agent_switching_friction artifact_clarity review_confidence resume_recovery reuse_next_project)
  for k in "${counts[@]}"; do [[ "$(val "$k")" =~ ^[0-9]+$ ]] || fail "metric $k must be a non-negative integer supplied by the owner"; done
  for k in "${ratings[@]}"; do [[ "$(val "$k")" =~ ^[1-5]$ ]] || fail "rating $k must be 1–5 supplied by the owner"; done
  [[ "$(val decision)" =~ ^(ACCEPT_NATIVE_STACK|TEST_CLINE|INVESTIGATE_RUFLO)$ ]] || fail "decision must be ACCEPT_NATIVE_STACK, TEST_CLINE or INVESTIGATE_RUFLO"

  gates="$(for f in "$REVIEWS_DIR"/HUMAN_GATE_*.md; do printf '%s=%s\n' "$(basename "$f" .md)" "$(sed -n 's/^\*\*Decision:\*\* //p' "$f")"; done)"
  gate_count="$(printf '%s\n' "$gates" | grep -c . || true)"
  repairs="$( (grep -lE '^\*\*Decision:\*\* REPAIR$' "$REVIEWS_DIR"/HUMAN_GATE_CONVERGE*.md 2>/dev/null || true) | wc -l | tr -d ' ')"
  runs="$(for d in .specify/workflows/runs/*/; do jq -r '"\(.created_at) \(.run_id) \(.status)"' "$d/state.json" 2>/dev/null; done | sort)"
  first="$(printf '%s\n' "$runs" | head -1 | cut -d' ' -f1)"
  elapsed_min="$(python3 -c "import datetime,sys; a=datetime.datetime.fromisoformat(sys.argv[1]); print(int((datetime.datetime.now(datetime.timezone.utc)-a).total_seconds()//60))" "$first")"
  ci_conclusion="$(jq -r '.conclusion // "unknown"' "$EVIDENCE_DIR/ci.json" 2>/dev/null || echo unknown)"
  {
    echo "### FR-013 experiment measurements"
    echo
    echo "Recorded $now in workflow run \`$run_id\`. Workflow-derived values come from Git and run state; owner-supplied values were passed verbatim as workflow inputs."
    echo
    echo "| Metric | Value | Source |"
    echo "|---|---|---|"
    echo "| Human gate records | $gate_count ($(printf '%s\n' "$gates" | tr '\n' ' ')) | Git: reviews/HUMAN_GATE_*.md |"
    echo "| Implementation repair cycles | $repairs | Git: convergence gate decisions |"
    echo "| Workflow runs | $(printf '%s\n' "$runs" | grep -c .) | local run state (see PLATFORM-POC-001-RUN-HISTORY.md) |"
    echo "| Elapsed time since first workflow run | ${elapsed_min} min (from $first) | run state |"
    echo "| CI result (last observed) | $ci_conclusion | evidence ci.json |"
    echo "| Manual copy/paste operations between agents | $(val manual_copy_paste) | owner |"
    echo "| Context re-explained | $(val context_reexplained) | owner |"
    echo "| Gaps found by Codex converge | $(val converge_gaps) | owner, from reviews/CONVERGE*.md |"
    echo "| Useful Grok findings not found by Codex/CI | $(val grok_unique_findings) | owner, from reviews/GROK_CRITIC.md |"
    echo "| Implementer scope deviations | $(val claude_scope_deviations) | owner |"
    echo "| Broken SDD artifacts | $(val broken_sdd_artifacts) | owner |"
    echo
    echo "| Rating (1–5) | Value |"
    echo "|---|---|"
    for k in "${ratings[@]}"; do echo "| ${k//_/ } | $(val "$k") |"; done
    echo
    echo "**Platform decision (owner):** $(val decision)"
  } > "$tmpmd"
  put_block "metrics" "$tmpmd"
  ;;
*) fail "unknown mode $mode" ;;
esac
check_protected_artifacts
pass "updated $RESULT_FILE ($mode)"
